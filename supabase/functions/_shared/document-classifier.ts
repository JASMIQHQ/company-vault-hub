export function normalizeDocumentType(value: string | null | undefined): VerifiedDocType | null {
  if (!value) return null;
  const normalized = value.trim().toUpperCase().replace(/\s+/g, " ");
  return (DOCUMENT_TYPES as readonly string[]).includes(normalized)
    ? (normalized as VerifiedDocType)
    : (DOCUMENT_TYPE_ALIASES[normalized] ?? null);
}
